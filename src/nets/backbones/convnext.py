'''
ConvNeXt-T + BiFPN backbone for SPNv2.

ConvNeXt-T stage outputs C2~C5 (strides 4/8/16/32) are fed into the original
SPNv2/EfficientDet BiFPN neck, which produces P2~P7. The heatmap and
segmentation heads follow the EfficientDet convention and read `features[0]`
(P2, stride 4).
'''

from __future__ import absolute_import
from __future__ import division
from __future__ import print_function

import logging

import torch.nn as nn
from torchvision.models import convnext_tiny, ConvNeXt_Tiny_Weights

from .bifpn import BiFPNLayer

logger = logging.getLogger(__name__)


class ConvNeXtBiFPN(nn.Module):
    """ ConvNeXt-T stages (C2~C5) followed by the original SPNv2/EfficientDet BiFPN.

    BiFPNLayer expects inputs [P1, P2, P3, P4, P5]; P6/P7 are generated by
    downsampling P5, exactly as in the EfficientDet backbone. Output is P2~P7,
    so the existing heads (and optionally the EfficientPose head) work unchanged.
    """
    def __init__(self, cfg, scaled_parameters):
        super(ConvNeXtBiFPN, self).__init__()

        # ImageNet weights when MODEL.BACKBONE.PRETRAINED is truthy
        weights = ConvNeXt_Tiny_Weights.IMAGENET1K_V1 \
            if cfg.MODEL.BACKBONE.PRETRAINED else None
        self.features = convnext_tiny(weights=weights).features

        # torchvision ConvNeXt-T stage layout:
        #   0 stem (stride 4), 1 stage1 (stride 4), 2 downsample + 3 stage2 (stride 8),
        #   4 downsample + 5 stage3 (stride 16), 6 downsample + 7 stage4 (stride 32)
        # Channel layout expected by BiFPNLayer: [P1, P2, P3, P4, P5]
        # (P1 is a placeholder and never used)
        self.feat_channels = [None, 96, 192, 384, 768]
        self.use_p2 = True

        bifpn_width = scaled_parameters['bifpn_width']
        self.bifpn = nn.Sequential(
            *[
                BiFPNLayer(self.feat_channels,
                           bifpn_width,
                           first_time=True if _ == 0 else False,
                           attention=True,
                           use_p2=self.use_p2,
                           use_group_norm=cfg.MODEL.USE_GROUPNORM_BACKBONE,
                           group_norm_size=cfg.MODEL.GROUPNORM_SIZE)
                for _ in range(scaled_parameters['bifpn_depth'])
            ]
        )

        self.out_channels = [bifpn_width] * 6          # P2 ~ P7
        self.out_strides  = [4, 8, 16, 32, 64, 128]
        self.head_in_channels = bifpn_width

    def forward(self, x):
        feats = []
        for i, blk in enumerate(self.features):
            x = blk(x)
            if i in (1, 3, 5, 7):
                feats.append(x)

        # [None, C2, C3, C4, C5] -> [P2, P3, P4, P5, P6, P7]
        return self.bifpn([None] + feats)
